import AppKit
import Defaults
import Logging
import Sauce

class Clipboard {
  static let shared = Clipboard()

  typealias OnNewCopyHook = (HistoryItem) -> Void

  private var onNewCopyHooks: [OnNewCopyHook] = []
  #if DEBUG
  // Runs after the pasteboard is inspected and before the copy is skipped or
  // recorded, so tests can change settings at that point.
  var afterInspectionForTesting: (() -> Void)?
  #endif
  var changeCount: Int

  private let pasteboard = NSPasteboard.general

  private var timer: Timer?
  private let ignoreRules = IgnoreRules()
  private let logger = Logger(label: AppIdentity.bundleIdentifier)

  private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
    .autoGenerated,
    .concealed,
    .transient
  ]
  private var sourceApp: NSRunningApplication? { NSWorkspace.shared.frontmostApplication }

  // Where capture settings live. See CaptureMode.
  let capturePreferences = Defaults.Keys.captureMode.suite
  // The effective capture mode at the previous check; nil before the first.
  private var lastCheckedCaptureMode: CaptureMode?
  private let captureSettingsChanges = CaptureSettingsChangeFlag()
  private var captureSettingsObservation: Defaults.Observation?

  init() {
    changeCount = pasteboard.changeCount
    // Synchronous for writes made in this process, so an in-app pause/resume is
    // seen even if no check runs in between.
    captureSettingsObservation = Defaults.observe(
      keys: .captureMode, .legacyIgnoreEvents, .legacyIgnoreOnlyNextEvent,
      options: []
    ) { @Sendable [captureSettingsChanges] in
      captureSettingsChanges.set()
    }
  }

  func onNewCopy(_ hook: @escaping OnNewCopyHook) {
    onNewCopyHooks.append(hook)
  }

  func clearHooks() {
    onNewCopyHooks = []
  }

  func start() {
    timer = Timer.scheduledTimer(
      timeInterval: Defaults[.clipboardCheckInterval],
      target: self,
      selector: #selector(checkForChangesInPasteboard),
      userInfo: nil,
      repeats: true
    )
  }

  func restart() {
    timer?.invalidate()
    start()
  }

  // Pause, resume or skip from the UI. Resuming or arming a skip also treats
  // everything already on the pasteboard as seen, so a copy made while paused is
  // never recorded and the skip applies to the very next copy.
  @discardableResult
  func perform(_ request: CaptureModeRequest) -> CaptureMode {
    let mode = CaptureMode.perform(request, in: capturePreferences)
    if mode != .paused {
      syncCaptureState()
    }
    return mode
  }

  // Marks the current pasteboard contents as seen under the current mode.
  func syncCaptureState() {
    changeCount = pasteboard.changeCount
    lastCheckedCaptureMode = CaptureMode.effective(in: capturePreferences)
    _ = captureSettingsChanges.take()
  }

  @MainActor
  func copyInMaccy(_ string: String) {
    pasteboard.clearContents()
    pasteboard.setString(string, forType: .string)
    pasteboard.setString(NSPasteboard.PasteboardType.fromMaccy.rawValue, forType: .source)
    sync()
    checkForChangesInPasteboard()
  }

  @MainActor
  func copy(_ item: HistoryItem?, removeFormatting: Bool = false) {
    guard let item else { return }

    pasteboard.clearContents()
    // Only representations that may be read now are written back, whatever
    // was stored under an earlier policy.
    // One value per type, the one shown, plus every copied file.
    let allowList = StoragePolicy.currentReadAllowList
    var contents = item.pasteboardContents(readableBy: allowList)

    if removeFormatting {
      contents = clearFormatting(contents)
    }

    for content in contents {
      guard content.type != NSPasteboard.PasteboardType.fileURL.rawValue else { continue }
      pasteboard.setData(content.value, forType: NSPasteboard.PasteboardType(content.type))
    }

    // Use writeObjects for file URLs so that multiple files that are copied actually work.
    // Only do this for file URLs because it causes an issue with some other data types (like formatted text)
    // where the item is pasted more than once.
    let fileURLItems: [NSPasteboardItem] = contents.compactMap { item in
      guard item.type == NSPasteboard.PasteboardType.fileURL.rawValue else { return nil }
      guard let value = item.value else { return nil }
      let pasteItem = NSPasteboardItem()
      pasteItem.setData(value, forType: NSPasteboard.PasteboardType(item.type))
      return pasteItem
    }
    pasteboard.writeObjects(fileURLItems)

    pasteboard.setString("", forType: .fromMaccy)
    pasteboard.setString(item.application ?? "", forType: .source)
    sync()

    Notifier.notify(for: item, sound: .knock)
    Task {
      checkForChangesInPasteboard()
    }
  }

  // Based on https://github.com/Clipy/Clipy/blob/develop/Clipy/Sources/Services/PasteService.swift.
  func paste() {
    Accessibility.check()

    // Add flag that left/right modifier key has been pressed.
    // See https://github.com/TermiT/Flycut/pull/18 for details.
    let cmdFlag = CGEventFlags(rawValue: UInt64(KeyChord.pasteKeyModifiers.rawValue) | 0x000008)
    var vCode = Sauce.shared.keyCode(for: KeyChord.pasteKey)

    // Force QWERTY keycode when keyboard layout switches to
    // QWERTY upon pressing ⌘ key (e.g. "Dvorak - QWERTY ⌘").
    // See https://github.com/p0deje/Maccy/issues/482 for details.
    if KeyboardLayout.current.commandSwitchesToQWERTY && cmdFlag.contains(.maskCommand) {
      vCode = KeyChord.pasteKey.QWERTYKeyCode
    }

    let source = CGEventSource(stateID: .combinedSessionState)
    // Disable local keyboard events while pasting
    source?.setLocalEventsFilterDuringSuppressionState([.permitLocalMouseEvents, .permitSystemDefinedEvents],
                                                       state: .eventSuppressionStateSuppressionInterval)

    let keyVDown = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: true)
    let keyVUp = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: false)
    keyVDown?.flags = cmdFlag
    keyVUp?.flags = cmdFlag
    keyVDown?.post(tap: .cgSessionEventTap)
    keyVUp?.post(tap: .cgSessionEventTap)
  }

  func clear() {
    guard Defaults[.clearSystemClipboard] else {
      return
    }

    pasteboard.clearContents()
  }

  @objc
  @MainActor
  func checkForChangesInPasteboard() { // swiftlint:disable:this cyclomatic_complexity function_body_length
    CaptureMode.absorbLegacyOneShot(in: capturePreferences)
    let storagePolicy = StoragePolicy.current
    let settingsChanged = captureSettingsChanges.take()
    let captureMode = CaptureMode.effective(in: capturePreferences)
    let previousCaptureMode = lastCheckedCaptureMode
    lastCheckedCaptureMode = captureMode

    guard pasteboard.changeCount != changeCount else {
      return
    }

    changeCount = pasteboard.changeCount

    let isFromMaccy = pasteboard.pasteboardItems?.contains(where: { $0.types.contains(.fromMaccy) }) == true
    if !isFromMaccy {
      // External copy occurred. Stop the current paste stack.
      // Maybe queue it into the paste stack? Configurable behaviour?
      AppState.shared.history.interruptPasteStack()
    }

    guard CaptureMode.changeIsAttributable(
      to: captureMode,
      previousMode: previousCaptureMode,
      settingsChanged: settingsChanged
    ) else {
      return
    }

    // While the storage setting is invalid nothing is captured.
    guard let allowList = storagePolicy.allowList else {
      return
    }

    // Reading types on NSPasteboard gives all the available
    // types - even the ones that are not present on the NSPasteboardItem.
    // See https://github.com/p0deje/Maccy/issues/241.
    if shouldIgnore(Set(pasteboard.types ?? []), storing: allowList) {
      return
    }

    if let sourceAppBundle = sourceApp?.bundleIdentifier, shouldIgnore(sourceAppBundle) {
      return
    }

    // Some applications (BBEdit, Edge) add 2 items to pasteboard when copying
    // so it's better to merge all data into a single record.
    // - https://github.com/p0deje/Maccy/issues/78
    // - https://github.com/p0deje/Maccy/issues/472
    // Ignore rules read the text of the string, file URL, RTF and HTML
    // representations whatever the storage setting, without storing it.
    let items = pasteboard.pasteboardItems ?? []
    guard !ignoreRules.rejects(items) else { return }

    // The record keeps one value per type: the one from the first pasteboard
    // item that has the type, which is the one `NSPasteboard.data(forType:)`
    // and `string(forType:)` hand to an app pasting this copy. Later values of
    // the same type are not read. File URLs are the exception: a Finder copy
    // of several files has one item per file, and every distinct file is kept
    // and pasted back as its own item.
    var contents = [HistoryItemContent]()
    var capturedTypes = Set<NSPasteboard.PasteboardType>()
    var capturedFileURLs = Set<Data>()
    var duplicatesDropped = 0
    // Size limits (see ContentLimits), checked as each representation is read.
    var tally = ContentLimits.Tally()
    var violation: ContentLimits.Violation?
    reading: for item in items {
      let types = Set(item.types)
      // Only representations that would be stored are read for this check.
      if allowList.allows(.string) && types.contains(.string) && isEmptyString(item) &&
          !richText(item, storing: allowList) {
        continue
      }

      // Only the allow-list is stored. Beyond the reads above, the data of any
      // other representation is never read. That also leaves out the Microsoft
      // Word link types and PDF that bookmarks and cross-references add
      // (https://github.com/p0deje/Maccy/issues/613,
      // https://github.com/p0deje/Maccy/issues/770).
      for type in item.types {
        guard allowList.allows(type) else { continue }
        if type != .fileURL && capturedTypes.contains(type) {
          duplicatesDropped += 1
          continue
        }
        guard case .store(let value) = allowList.admission(of: type, value: item.data(forType: type)) else {
          continue
        }
        if let exceeded = tally.add(type, bytes: value?.count ?? 0) {
          violation = exceeded
          break reading
        }
        if type == .fileURL {
          // A file URL without data has nothing to paste.
          guard let value else { continue }
          guard capturedFileURLs.insert(value).inserted else {
            duplicatesDropped += 1
            continue
          }
        }
        capturedTypes.insert(type)
        contents.append(HistoryItemContent(type: type.rawValue, value: value))
      }
    }
    // A copy over a limit is not recorded at all, and doesn't use up skip next.
    if let violation {
      logger.warning("Copy not recorded: \(violation.description)")
      return
    }
    if duplicatesDropped > 0 {
      logger.info(
        "Copy of \(items.count) pasteboard items kept one value per type; \(duplicatesDropped) duplicates not stored"
      )
    }

    // Metadata alone is not a copy worth recording.
    guard allowList.hasStorableContent(contents.map { NSPasteboard.PasteboardType($0.type) }) else {
      return
    }

    #if DEBUG
    afterInspectionForTesting?()
    #endif

    if captureMode == .skipNext {
      // This copy would have been recorded, so it is the one to skip. Maccy's
      // own writes don't count. The storage setting may have changed while
      // the pasteboard was inspected, so whether the copy would be recorded
      // is decided again with the setting read now: a copy `add` would refuse
      // doesn't use up the skip.
      let isMaccySource = pasteboard.string(forType: .source) == NSPasteboard.PasteboardType.fromMaccy.rawValue
      guard let currentAllowList = StoragePolicy.current.allowList,
            currentAllowList.hasStorableContent(contents.map { NSPasteboard.PasteboardType($0.type) }) else {
        return
      }
      if !isFromMaccy && !isMaccySource {
        CaptureMode.consumeSkip(in: capturePreferences)
        // The watcher's own write is not an uncertain transition, so the copy
        // after the skipped one is recorded.
        syncCaptureState()
      }

      return
    }

    let historyItem = HistoryItem(contents: contents)

    if #unavailable(macOS 15.0) {
      // On macOS 14 the history item needs to be inserted into storage directly after creating it.
      // Insertion applies the storage policy first and can refuse the item.
      guard History.shared.insertIntoStorage(historyItem) else {
        return
      }
    }

    historyItem.application = sourceApp?.bundleIdentifier
    historyItem.regenerateTitle()

    onNewCopyHooks.forEach({ $0(historyItem) })
  }

  private func shouldIgnore(_ types: Set<NSPasteboard.PasteboardType>, storing allowList: StorageAllowList) -> Bool {
    let ignoredTypes = self.ignoredTypes
      .union(Defaults[.ignoredPasteboardTypes].map({ NSPasteboard.PasteboardType($0) }))

    return types.isDisjoint(with: allowList.enabledTypes) ||
      !types.isDisjoint(with: ignoredTypes)
  }

  private func shouldIgnore(_ sourceAppBundle: String) -> Bool {
    if Defaults[.ignoreAllAppsExceptListed] {
      return !Defaults[.ignoredApps].contains(sourceAppBundle)
    } else {
      return Defaults[.ignoredApps].contains(sourceAppBundle)
    }
  }

  private func isEmptyString(_ item: NSPasteboardItem) -> Bool {
    guard let string = item.string(forType: .string) else {
      return true
    }

    return string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
  }

  private func richText(_ item: NSPasteboardItem, storing allowList: StorageAllowList) -> Bool {
    // RTF is imported only within RichTextImport's bounds. HTML is scanned,
    // never rendered, so nothing it refers to is loaded.
    if allowList.allows(.rtf), let rtf = item.data(forType: .rtf) {
      if let text = RichTextImport.text(fromRTF: rtf) {
        return !text.isEmpty
      }
    }

    if allowList.allows(.html), let html = item.data(forType: .html) {
      return ClipboardHTMLText.hasContent(html)
    }

    return false
  }

  // Some applications requires window be unfocused and focused back to sync the clipboard.
  // - Chrome Remote Desktop (https://github.com/p0deje/Maccy/issues/948)
  // - Netbeans (https://github.com/p0deje/Maccy/issues/879)
  private func sync() {
    guard let app = sourceApp,
          app.bundleURL?.lastPathComponent == "Chrome Remote Desktop.app" ||
            app.localizedName?.contains("NetBeans") == true else {
      return
    }

    NSApp.activate(ignoringOtherApps: true)
    NSApp.hide(self)
  }

  private func clearFormatting(_ contents: [HistoryItemContent]) -> [HistoryItemContent] {
    var newContents: [HistoryItemContent] = contents
    // `contents` holds at most one plain-text value (`pasteboardContents`), so
    // a plain paste writes exactly one string.
    let stringContents = Array(contents.filter { NSPasteboard.PasteboardType($0.type) == .string }.prefix(1))

    // If there is no string representation of data,
    // behave like we didn't have to remove formatting.
    if !stringContents.isEmpty {
      newContents = stringContents

      // Preserve file URLs.
      // https://github.com/p0deje/Maccy/issues/962
      let fileURLContents = contents.filter { NSPasteboard.PasteboardType($0.type) == .fileURL }
      if !fileURLContents.isEmpty {
        newContents += fileURLContents
      }
    }

    return newContents
  }
}

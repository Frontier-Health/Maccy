    // MARK: Helpers

    private func turn(_ toggle: StorageType, on isOn: Bool) {
      Defaults[.enabledPasteboardTypes] = StoragePolicy.current.enabledTypes(setting: toggle, to: isOn)
    }

    private func copy(_ representations: [NSPasteboard.PasteboardType: Data]) {
      let item = NSPasteboardItem()
      for (type, data) in representations {
        item.setData(data, forType: type)
      }
      pasteboard.clearContents()
      pasteboard.writeObjects([item])
    }

    // Runs one production watcher check now and returns what it recorded.
    private func checkNow() -> [HistoryItem] {
      var copies: [HistoryItem] = []
      clipboard.clearHooks()
      clipboard.onNewCopy { copies.append($0) }
      clipboard.checkForChangesInPasteboard()
      clipboard.clearHooks()
      return copies
    }

    // An item written straight to the store, as an earlier policy might have.
    private func storedItem(_ representations: [NSPasteboard.PasteboardType: Data]) -> HistoryItem {
      let item = HistoryItem()
      Storage.shared.context.insert(item)
      item.contents = representations
        .sorted { $0.key.rawValue < $1.key.rawValue }
        .map { HistoryItemContent(type: $0.key.rawValue, value: $0.value) }
      item.regenerateTitle(recognizingImageText: false)
      try? Storage.shared.context.save()
      return item
    }

    private struct InjectedFailure: Error {}

    // Each content's type and value, in a stable order.
    private func contentValues(_ item: HistoryItem) -> [String] {
      item.contents.map { "\($0.type)=\($0.value?.base64EncodedString() ?? "nil")" }.sorted()
    }

    // Every stored item with its pin and every representation's value, as a
    // second context sees them.
    private func storedValues() throws -> [String] {
      let context = ModelContext(Storage.shared.container)
      let items = try context.fetch(FetchDescriptor<HistoryItem>()).map { item in
        "item pin=\(item.pin ?? "-") " + contentValues(item).joined(separator: ",")
      }
      let contents = try context.fetch(FetchDescriptor<HistoryItemContent>()).map {
        "content \($0.type)=\($0.value?.base64EncodedString() ?? "nil")"
      }
      return (items + contents).sorted()
    }

    private func pngData() throws -> Data {
      let rep = try #require(NSBitmapImageRep(
        bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2, bitsPerSample: 8, samplesPerPixel: 4,
        hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
      ))
      return try #require(rep.representation(using: .png, properties: [:]))
    }

    // Every stored item and representation, as a second context sees them.
    private func storedSnapshot() throws -> [String] {
      let context = ModelContext(Storage.shared.container)
      let items = try context.fetch(FetchDescriptor<HistoryItem>()).map { item in
        "item \(item.displayTitle(readableBy: .everything)) pin=\(item.pin ?? "-") " +
          item.contents.map(\.type).sorted().joined(separator: ",")
      }
      let contents = try context.fetch(FetchDescriptor<HistoryItemContent>()).map { "content \($0.type)" }
      return (items + contents).sorted()
    }

    private func expectStoredTypes(
      _ expected: [String],
      fileID: String = #fileID,
      filePath: String = #filePath,
      line: Int = #line,
      column: Int = #column
    ) throws {
      let sourceLocation = SourceLocation(fileID: fileID, filePath: filePath, line: line, column: column)
      let context = Storage.shared.context
      context.processPendingChanges()
      try context.save()
      let stored = try context.fetch(FetchDescriptor<HistoryItemContent>()).map(\.type)
      #expect(stored.sorted() == expected.sorted(), sourceLocation: sourceLocation)
    }
  }
}

// What each save wrote, collected from a notification observer.
final class SavedContentLog: @unchecked Sendable {
  private(set) var entries: [[String]] = []

  func append(_ entry: [String]) {
    entries.append(entry)
  }
}

extension History {
  // Adds an item the test expects to be stored.
  @MainActor
  @discardableResult
  func added(_ item: HistoryItem, sourceLocation: SourceLocation = #_sourceLocation) -> HistoryItemDecorator {
    guard let decorator = add(item) else {
      Issue.record("History refused an item the test expected it to store", sourceLocation: sourceLocation)
      return HistoryItemDecorator(item)
    }
    return decorator
  }
}

// The raw storage preference, so a test can start from none and restore it.
struct SavedStoragePreference: @unchecked Sendable {
  let defaults = Defaults.Keys.enabledPasteboardTypes.suite
  let value: Any?

  init() {
    value = defaults.object(forKey: StoragePolicy.preferenceKey)
  }

  func restore() {
    if let value {
      defaults.set(value, forKey: StoragePolicy.preferenceKey)
    } else {
      defaults.removeObject(forKey: StoragePolicy.preferenceKey)
    }
  }
}
